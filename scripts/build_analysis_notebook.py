def build() -> Path:
    nb = nbf.v4.new_notebook()
    nb.metadata = {"colab": {"provenance": []}, "kernelspec": {"display_name": "Python 3", "language": "python",
                                                              "name": "python3"}, "language_info": {"name": "python"}}
    md = nbf.v4.new_markdown_cell
    code = nbf.v4.new_code_cell
    nb.cells = [
        md(INTRO), code(BOOTSTRAP), code(CONFIG), code(INVENTORY),
        md("## Run\nOne call performs the audit, catalog construction, matching, rule fitting, controls, figures and report. "
           "Re-running skips runs whose prediction-file hash and analysis version are unchanged."),
        code(RUN),
        md("## Audit\nInteger counts come from raw per-example records (not rounded summaries). `attribution_blocked` runs are "
           "excluded from all explanatory analyses."), code(AUDIT), code(CATALOG),
        md("## What the models output\nCategories: *correct*; *wrong: unique legal* (exactly one of the 288 transformations "
           "reproduces the prediction); *wrong: ambiguous legal* (several do, e.g. symmetric inputs); *no legal match*. "
           "A match does not identify which symbolic string was executed."), code(MATCH), code(HYP),
        md("## Is the behaviour a stable rule?\nRules are fitted to **model predictions** (never targets) on the FIT half of "
           "the base grids and scored on the disjoint DIAG half. Many-to-one source-copy maps and bijective permutations are "
           "kept distinct; tie-driven/low-fidelity maps are flagged rather than called learned rules."), code(STABLE),
        md("## Composition and the half-period ambiguity\nWith Z = shift by (3, 3), the generators ZA, ZB, ZC reproduce every "
           "length-2 training example exactly but predict Z(target) for odd lengths. This checks an explicit explanation; it does "
           "not by itself show that this ambiguity caused the behaviour, and it cannot explain failures on unseen pairs."),
        code(COMP), code(CTRL), code(PAIRED), code(EXAMPLES), code(REPORT),
        md("## Outputs\n`<DIAGNOSTICS_OUTPUT_DIR>/`: `tables/` (CSV), `figures/` (PNG+PDF+CSV), `per_example/` (compact "
           "per-record diagnostics), `maps/` (all fitted source maps), `REPORT.md`, `provenance.json` (file hashes, selected "
           "steps, analysis code commit), `cache/`. Original predictions and checkpoints are only read."),
    ]
    p = ROOT / "notebooks" / "03_analyze_generalization_failures.ipynb"
    nbf.validate(nb)
    nbf.write(nb, p)
    return p


if __name__ == "__main__":
    print(build())
