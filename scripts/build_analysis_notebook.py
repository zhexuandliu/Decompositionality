INTRO = """# What do the models output on unseen instructions? — post-hoc diagnostics for BOTH experiments

This notebook **does not train, fine-tune or re-select anything**. It reads the *saved* test predictions of all
trained models from both experiments (`distinct_pairs`, `all_pairs`) and asks what the models systematically output
on strings they were not trained on (singles, unseen pairs, all 27 triples).

**Task reminder.** 6x6 grids of digits 0-9; `A` = shift right by one with wrap, `B` = rotate 90° clockwise,
`C` = mirror left-right; strings run **left to right** (`AB` = B(A(X))).

**What is measured** (all on frozen predictions):
1. *Audit*: integer exact/cell counts recomputed from raw records; stored targets re-derived by an independent oracle;
   grid/string alignment across models and experiments; free-running vs teacher-forced provenance.
2. *Legal-transformation matching*: every prediction is compared with **all 288** transformations generated by A, B, C
   (36 translations x 8 square orientations). Exact matches can be unique, ambiguous, or absent.
3. *Pre-declared error hypotheses* (identity, first/last op, prefixes/suffixes, dropped/reordered ops, collapsed repeats,
   doubled singles, training-pair transformations).
4. *Stability across grids*: one fixed transformation, a bijective source permutation, and a many-to-one source-copy
   map are **fitted to model predictions on half of the base grids** and evaluated on the other half (DIAG split).
5. *Composition consistency* of the fitted single-operation maps, and the explicit **half-period ambiguity**
   A'=ZA, B'=ZB, C'=ZC (Z = shift by 3 right and 3 down), which leaves every length-2 string unchanged.
6. *Calibration controls* showing why exact accuracy 0 with cell accuracy ~0.10 can still be a perfectly structured error.

**Interpretation limits.** Behavioural compatibility is not a mechanistic or causal claim; DIAG-split fidelities
describe frozen predictions and are not a new benchmark; one training seed only.
"""

