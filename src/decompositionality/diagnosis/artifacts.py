@dataclass
class Run:
    experiment: str
    model: str
    source: str                      # "original" | "regenerated"
    files: Dict[str, str]
    X: np.ndarray                    # [N,36] int8
    Y: np.ndarray                    # [N,36] stored targets
    P: np.ndarray                    # [N,36] predictions, -1 = invalid
    grid_id: np.ndarray
    string: np.ndarray
    stored: Dict[str, np.ndarray]
    meta: dict = field(default_factory=dict)
    audit: dict = field(default_factory=dict)

    @property
    def key(self) -> str:
        return f"{self.experiment}/{self.model}"


def load_run(experiment: str, model: str, npz_path: Path, source: str = "original",
             eval_summary: Optional[Path] = None, extra_files: Optional[Dict[str, Path]] = None,
             hash_files: bool = True) -> Run:
    npz_path = Path(npz_path)
    with np.load(npz_path, allow_pickle=False) as z:
        raw = {k: z[k] for k in z.files}
    missing = [k for k in ("pred", "target", "input", "grid_id", "string") if k not in raw]
    if missing:
        raise ValueError(f"{npz_path}: missing arrays {missing}")
    n = len(raw["grid_id"])
    for k in ("pred", "target", "input"):
        if raw[k].reshape(n, -1).shape[1] != 36:
            raise ValueError(f"{npz_path}: {k} has malformed shape {raw[k].shape}")
    strings = raw["string"].astype(str)
    order = np.lexsort((raw["grid_id"], strings))  # deterministic order independent of file order
    files = {"predictions": str(npz_path)}
    hashes = {"predictions": sha256_file(npz_path) if hash_files else None}
    meta = {}
    if eval_summary is not None and Path(eval_summary).exists():
        files["eval_summary"] = str(eval_summary)
        hashes["eval_summary"] = sha256_file(Path(eval_summary)) if hash_files else None
        meta = json.loads(Path(eval_summary).read_text())
    for name, p in (extra_files or {}).items():
        if p is not None and Path(p).exists():
            files[name] = str(p)
            hashes[name] = sha256_file(Path(p)) if hash_files else None
    stored = {k: raw[k][order] for k in ("valid", "cell_correct", "exact", "cell_ce", "eos_ok") if k in raw}
    run = Run(experiment, model, source, files,
              X=raw["input"].reshape(n, 36)[order].astype(np.int16),
              Y=raw["target"].reshape(n, 36)[order].astype(np.int16),
              P=raw["pred"].reshape(n, 36)[order].astype(np.int16),
              grid_id=raw["grid_id"][order].astype(np.int64), string=strings[order], stored=stored, meta=meta)
    run.meta["file_sha256"] = hashes
    return run


def load_experiment_runs(experiment: str, exp_dir: Path, models: Sequence[str], regenerated_root: Optional[Path] = None,
                         hash_checkpoints: bool = True, log=print) -> List[Run]:
    runs = []
    for m in models:
        ev = exp_dir / "eval" / m
        orig = ev / "test_predictions.npz"
        regen = (regenerated_root / experiment / m / "test_predictions.npz") if regenerated_root else None
        extra = {"run_config": exp_dir / "runs" / m / "run_config.json"}
        if hash_checkpoints:
            extra["best_checkpoint"] = exp_dir / "runs" / m / "best.pt"
        if orig.exists():
            runs.append(load_run(experiment, m, orig, "original", ev / "eval_summary.json", extra))
        elif regen is not None and regen.exists():
            runs.append(load_run(experiment, m, regen, "regenerated", regen.parent / "regeneration_provenance.json", extra))
        else:
            log(f"  [{experiment}/{m}] no predictions -> skipped (listed as missing in the inventory)")
    return runs


def load_manifest_grids(exp_dir: Path) -> Optional[np.ndarray]:
    p = exp_dir / "manifests" / "heldout_grids.npz"
    if not p.exists():
        return None
    with np.load(p) as z:
        return z["test_grids"].reshape(len(z["test_grids"]), 36).astype(np.int16)


