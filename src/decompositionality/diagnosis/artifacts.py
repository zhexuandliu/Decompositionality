"""Artifact discovery, read-only loading and auditing of saved test predictions (torch-free).

Expected layout (written by ``pipeline.evaluate_model``)::

    <experiment_dir>/manifests/{heldout_grids.npz, manifest.json}
    <experiment_dir>/eval/<model>/{test_predictions.npz, eval_summary.json, EVAL_COMPLETE.json}
    <experiment_dir>/runs/<model>/{best.pt, state.pt, run_config.json, train_summary.json}

``test_predictions.npz`` keys: pred/target/input [N,6,6] int8, grid_id, string, valid, cell_correct,
exact, cell_ce, and (AR models) eos_ok. In ``pred``, -1 marks a non-digit token produced during
free-running decoding (the raw token IDs were not stored by the evaluation code); such cells are
invalid and always wrong. Source files are opened read-only and never modified.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import numpy as np

from .. import operations as O
from ..names import DISPLAY_NAMES, MODEL_IDS
from . import group as G

AR_MODELS = {"transformer_ar", "looped_transformer_ar"}
GROUPS7 = ["singles", "pairs_seen", "pairs_unseen", "triples_all_distinct", "triples_two_types", "triples_one_type",
           "triples_all"]


def sha256_file(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def grid_hash_rows(grids: np.ndarray) -> np.ndarray:
    g = np.ascontiguousarray(np.asarray(grids).reshape(len(grids), -1).astype(np.uint8))
    return np.array([hashlib.sha256(r.tobytes()).hexdigest()[:16] for r in g])


def diag_group(s: str, train_strings: Sequence[str]) -> str:
    if len(s) == 2:
        return "pairs_seen" if s in set(train_strings) else "pairs_unseen"
    return O.string_group(s)


