def discover_models(exp_dir: Path, regenerated_dir: Optional[Path] = None) -> List[str]:
    found = set()
    for base in [exp_dir / "eval", exp_dir / "runs"] + ([regenerated_dir] if regenerated_dir else []):
        if base and base.exists():
            found |= {p.name for p in base.iterdir() if p.is_dir()}
    known = [m for m in MODEL_IDS if m in found]
    return known + sorted(found - set(MODEL_IDS))


def inventory(experiment_dirs: Dict[str, str], regenerated_root: Optional[Path] = None, models: Optional[Sequence[str]] = None):
    import pandas as pd
    rows = []
    for exp, d in experiment_dirs.items():
        d = Path(d)
        regen = (regenerated_root / exp) if regenerated_root else None
        mids = list(models) if models else (discover_models(d, regen) if d.exists() else list(MODEL_IDS))
        for m in mids:
            ev, rn = d / "eval" / m, d / "runs" / m
            rg = (regen / m / "test_predictions.npz") if regen else None
            r = {"experiment": exp, "model": m, "experiment_dir": str(d), "experiment_dir_exists": d.exists(),
                 "manifest": (d / "manifests" / "heldout_grids.npz").exists(),
                 "original_predictions": (ev / "test_predictions.npz").exists(),
                 "eval_summary": (ev / "eval_summary.json").exists(),
                 "best_checkpoint": (rn / "best.pt").exists(), "last_checkpoint": (rn / "state.pt").exists(),
                 "run_config": (rn / "run_config.json").exists(),
                 "regenerated_predictions": bool(rg and rg.exists())}
            if r["original_predictions"]:
                r["status"] = "predictions available (original)"
            elif r["regenerated_predictions"]:
                r["status"] = "predictions available (regenerated by frozen inference)"
            elif r["best_checkpoint"] and r["run_config"] and r["manifest"]:
                r["status"] = "MISSING predictions; selected checkpoint available (frozen inference possible)"
            else:
                r["status"] = "MISSING: no predictions and no usable checkpoint -> analysis unavailable"
            rows.append(r)
    return pd.DataFrame(rows)


