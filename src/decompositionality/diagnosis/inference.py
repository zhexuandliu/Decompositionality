"""OPT-IN frozen inference to regenerate MISSING test predictions from the already-selected checkpoint.

Only used when RUN_FROZEN_INFERENCE_IF_MISSING=True. It loads ``runs/<model>/best.pt`` (the checkpoint
selected during training by seen-pair validation CE -- never re-selected here), rebuilds the original
39-string test set from the saved manifest, and predicts with model.eval(), torch.no_grad(), frozen
parameters, freshly reset recurrent state and NO optimizer. Outputs go to a separate folder with
provenance; original artifacts are never touched.
"""
from __future__ import annotations

import json
import time
from pathlib import Path


def regenerate_one(experiment: str, model_id: str, exp_dir: Path, out_dir: Path, log=print) -> dict:
    import numpy as np
    import torch

    from .. import operations as O
    from ..data import make_eval_set
    from ..evaluation import run_model_on_set, save_eval_outputs
    from ..models.registry import build_model
    from ..utils import git_commit, resolve_amp_dtype, resolve_device
    from .artifacts import sha256_file

    rdir = exp_dir / "runs" / model_id
    rc = json.loads((rdir / "run_config.json").read_text())
    ck = torch.load(rdir / "best.pt", map_location="cpu", weights_only=False)
    if ck.get("config_hash") != rc.get("config_hash"):
        raise RuntimeError(f"{experiment}/{model_id}: best.pt config hash does not match run_config.json")
    with np.load(exp_dir / "manifests" / "heldout_grids.npz") as z:
        test_grids = z["test_grids"]
    n_test = rc.get("full_experiment_config", {}).get("n_test_grids", 1000)
    es = make_eval_set(test_grids[:n_test], O.TEST_STRINGS, "test")
    device = resolve_device("auto")
    amp = resolve_amp_dtype(device, "auto")
    model = build_model(model_id, rc["model_config"]).to(device)
    model.load_state_dict(ck["model"])
    model.eval()
    for p in model.parameters():
        p.requires_grad_(False)
    t = time.time()
    res = run_model_on_set(model, es, device, amp)   # eval + no_grad inside; predictions never see targets
    dst = out_dir / experiment / model_id
    summ = save_eval_outputs(dst, es, res, {"experiment": experiment, "model_id": model_id, "seed": rc["train"]["seed"]},
                             O.TRAIN_SETS[experiment], "test")
    prov = {"kind": "REGENERATED by frozen inference (not the original evaluation artifact)",
            "experiment": experiment, "model_id": model_id, "checkpoint": str(rdir / "best.pt"),
            "checkpoint_sha256": sha256_file(rdir / "best.pt"), "selected_step": ck.get("step"),
            "config_hash": ck.get("config_hash"), "decoding": model.cost_info()["decoding"],
            "repo_commit": git_commit(), "device": str(device), "seconds": time.time() - t, "summary": summ,
            "optimizer_created": False}
    (dst / "regeneration_provenance.json").write_text(json.dumps(prov, indent=1, default=str))
    log(f"  regenerated {experiment}/{model_id} from best.pt (step {ck.get('step')}) in {prov['seconds']:.0f}s")
    del model
    return prov


def regenerate_missing(inv, exp_dirs, out_dir: Path, log=print) -> list:
    done = []
    todo = inv[(~inv.original_predictions) & (~inv.regenerated_predictions) & inv.best_checkpoint & inv.run_config & inv.manifest]
    for _, r in todo.iterrows():
        try:
            done.append(regenerate_one(r.experiment, r.model, Path(exp_dirs[r.experiment]), out_dir, log))
        except Exception as exc:
            log(f"  regeneration FAILED for {r.experiment}/{r.model}: {exc!r}")
            done.append({"experiment": r.experiment, "model_id": r.model, "error": repr(exc)})
    if not len(todo):
        log("Frozen inference: nothing to regenerate.")
    return done
