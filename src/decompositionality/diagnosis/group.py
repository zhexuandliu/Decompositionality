"""Finite transformation catalog for the 6x6 periodic grid (torch-free).

Source-index convention
-----------------------
A transformation is a length-36 integer array ``p`` with
``apply(p, X).reshape(-1)[j] = X.reshape(-1)[p[j]]`` (output cell ``j`` copies source cell ``p[j]``).
Applying ``p`` FIRST and then ``q`` gives ``X[p][q] = X[p[q]]``, so
``compose(first=p, second=q) = p[q]``. Words execute LEFT TO RIGHT ("AB" = A then B).

The generators are defined here independently of ``decompositionality.operations`` from the
coordinate formulas (an independent oracle):

    A(X)[r,c] = X[r,(c-1) mod 6]   B(X)[r,c] = X[5-c,r]   C(X)[r,c] = X[r,5-c]

The group generated by A, B, C has 288 elements (36 translations x 8 square orientations).
IDs are assigned by breadth-first search from the identity with generator order A, B, C, so each
element's representative word is a shortest word (first found in that order).
"""
from __future__ import annotations

import hashlib
import itertools
from collections import deque
from typing import Dict, List, Sequence

import numpy as np

N = 6
NC = N * N
GENERATOR_ORDER = ("A", "B", "C")


def _src(fn) -> np.ndarray:
    return np.array([fn(r, c) for r in range(N) for c in range(N)], dtype=np.int64)


A_SRC = _src(lambda r, c: r * N + (c - 1) % N)
B_SRC = _src(lambda r, c: (N - 1 - c) * N + r)
C_SRC = _src(lambda r, c: r * N + (N - 1 - c))
Z_SRC = _src(lambda r, c: ((r - 3) % N) * N + (c - 3) % N)   # shift right 3 AND down 3
IDENTITY = np.arange(NC, dtype=np.int64)
GENERATORS = {"A": A_SRC, "B": B_SRC, "C": C_SRC}


def compose(first: np.ndarray, second: np.ndarray) -> np.ndarray:
    """Apply ``first`` then ``second``."""
    return np.asarray(first)[np.asarray(second)]


def word_perm(word: str) -> np.ndarray:
    p = IDENTITY.copy()
    for ch in word:
        p = compose(p, GENERATORS[ch])
    return p


def apply_perm(p: np.ndarray, X: np.ndarray) -> np.ndarray:
    """X: [..., 36] or [..., 6, 6]; returns the same layout."""
    X = np.asarray(X)
    flat = X.reshape(X.shape[:-2] + (NC,)) if X.shape[-2:] == (N, N) else X
    out = flat[..., np.asarray(p)]
    return out.reshape(X.shape)


def oracle_apply_string(X: np.ndarray, word: str) -> np.ndarray:
    """Independent reference oracle: apply a word left to right."""
    return apply_perm(word_perm(word), X)


def is_bijection(p: np.ndarray) -> bool:
    return np.array_equal(np.sort(p), IDENTITY)


def inverse(p: np.ndarray) -> np.ndarray:
    inv = np.empty_like(p)
    inv[p] = IDENTITY
    return inv


def translation(dr: int, dc: int) -> np.ndarray:
    return _src(lambda r, c: ((r - dr) % N) * N + (c - dc) % N)


def d4_orientations() -> List[np.ndarray]:
    """The 8 orientations about the grid centre: B^k and B^k followed by C."""
    out, p = [], IDENTITY.copy()
    for _ in range(4):
        out.append(p)
        out.append(compose(p, C_SRC))
        p = compose(p, B_SRC)
    return out


class Catalog:
    """All group elements with deterministic IDs and shortest representative words."""

    def __init__(self):
        perms: List[np.ndarray] = [IDENTITY.copy()]
        words: List[str] = [""]
        index: Dict[bytes, int] = {IDENTITY.tobytes(): 0}
        queue = deque([0])
        while queue:
            i = queue.popleft()
            for g in GENERATOR_ORDER:
                q = compose(perms[i], GENERATORS[g])
                key = q.tobytes()
                if key not in index:
                    index[key] = len(perms)
                    perms.append(q)
                    words.append(words[i] + g)
                    queue.append(index[key])
        self.perms = np.stack(perms).astype(np.int64)          # [288, 36]
        self.words = words
        self._index = index
        self.size = len(perms)
        self.mult = np.array([[index[compose(p, GENERATORS[g]).tobytes()] for g in GENERATOR_ORDER] for p in perms])
        self.inverse_ids = np.array([index[inverse(p).tobytes()] for p in perms])
        self.z_id = self.id_of(Z_SRC)

    def id_of(self, p: np.ndarray) -> int:
        """Group ID, or -1 if ``p`` is not one of the 288 transformations."""
        return self._index.get(np.asarray(p, dtype=np.int64).tobytes(), -1)

    def word_id(self, word: str) -> int:
        return self.id_of(word_perm(word))

    def compose_ids(self, i: int, j: int) -> int:
        return self.id_of(compose(self.perms[i], self.perms[j]))

    def label(self, gid: int) -> str:
        if gid < 0:
            return "not-in-group"
        return self.words[gid] or "I"

    def alt_generator_id(self, word: str) -> int:
        """Prediction of the alternate generators A'=ZA, B'=ZB, C'=ZC: Z^len(word) o truth."""
        tid = self.word_id(word)
        return self.compose_ids(tid, self.z_id) if len(word) % 2 == 1 else tid

    def digest(self) -> str:
        return hashlib.sha256(self.perms.astype(np.int16).tobytes()).hexdigest()[:16]

    def table(self):
        import pandas as pd
        rows = []
        for i, p in enumerate(self.perms):
            rows.append({"group_id": i, "canonical_word": self.label(i), "word_length": len(self.words[i]),
                         "inverse_id": int(self.inverse_ids[i]), "times_A": int(self.mult[i, 0]),
                         "times_B": int(self.mult[i, 1]), "times_C": int(self.mult[i, 2]),
                         "fixed_cells": int((p == IDENTITY).sum()), "source_index_map": " ".join(map(str, p))})
        return pd.DataFrame(rows)


def check_catalog(cat: Catalog) -> dict:
    """Assert the structural properties used by the diagnostics."""
    assert cat.size == 288, cat.size
    assert all(is_bijection(p) for p in cat.perms)
    assert np.array_equal(cat.perms[0], IDENTITY)
    for i in range(cat.size):
        assert np.array_equal(compose(cat.perms[i], cat.perms[cat.inverse_ids[i]]), IDENTITY)
        for k, g in enumerate(GENERATOR_ORDER):
            assert cat.id_of(compose(cat.perms[i], GENERATORS[g])) == cat.mult[i, k] >= 0
    # independent cross-check: 36 translations x 8 orientations
    alt = {compose(o, translation(dr, dc)).tobytes() for o in d4_orientations() for dr in range(N) for dc in range(N)}
    assert alt == set(cat._index), "catalog != translations x D4"
    # Z properties
    Z = Z_SRC
    assert np.array_equal(compose(Z, Z), IDENTITY) and not np.array_equal(Z, IDENTITY)
    for g in GENERATORS.values():
        assert np.array_equal(compose(Z, g), compose(g, Z))
    assert cat.z_id >= 0
    # representative words reproduce their elements and are shortest (BFS)
    for i, w in enumerate(cat.words):
        assert cat.id_of(word_perm(w)) == i
    return {"size": cat.size, "z_id": cat.z_id, "z_word": cat.label(cat.z_id), "max_word_length": max(map(len, cat.words)),
            "digest": cat.digest()}


def string_classes(cat: "Catalog", labels: Sequence[str], train_labels: Sequence[str], pair_words: Sequence[str] = ()):
    """Equivalence classes of evaluated words (labels; "EMPTY" = identity). Words with the same
    transformation are aliases. STRING novelty and TRANSFORMATION novelty are tracked separately, and
    original length-two pair transformations are tracked separately from all training transformations."""
    import pandas as pd
    from ..words import from_label
    train_ids = {cat.word_id(from_label(s)) for s in train_labels}
    pair_ids = {cat.word_id(w) for w in pair_words}
    ids = {s: cat.word_id(from_label(s)) for s in labels}
    rows = []
    for s in labels:
        gid = ids[s]
        rows.append({"string": s, "length": len(from_label(s)), "group_id": gid, "canonical_word": cat.label(gid),
                     "string_in_training": s in set(train_labels),
                     "transformation_in_training": gid in train_ids,
                     "transformation_is_original_pair": gid in pair_ids,
                     "alt_generator_id": cat.alt_generator_id(from_label(s)),
                     "alt_generator_word": cat.label(cat.alt_generator_id(from_label(s))),
                     "n_evaluated_aliases": sum(1 for t in labels if t != s and ids[t] == gid),
                     "evaluated_aliases": " ".join([t for t in labels if t != s and ids[t] == gid][:12])})
    return pd.DataFrame(rows)


