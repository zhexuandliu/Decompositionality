def expected_wrong_perm_cell_accuracy(p: np.ndarray, q: np.ndarray, n_digits: int = 10) -> float:
    """For iid uniform digits: k/36 + (1 - k/36)/n_digits where k = #positions with p[j] == q[j]."""
    k = int((np.asarray(p) == np.asarray(q)).sum())
    return k / NC + (1 - k / NC) / n_digits


def exact_agreement_log10_probability(p: np.ndarray, q: np.ndarray) -> int:
    """log10 P(X[p] == X[q] exactly) for iid uniform digits = (#components - 36), where the
    components are those of the graph joining source cells p[j] and q[j]."""
    parent = list(range(NC))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for a, b in zip(np.asarray(p), np.asarray(q)):
        ra, rb = find(int(a)), find(int(b))
        if ra != rb:
            parent[ra] = rb
    comps = len({find(i) for i in range(NC)})
    return comps - NC
